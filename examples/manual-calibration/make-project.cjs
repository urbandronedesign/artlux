// Writes manual-calibration.artlux — the template for calibrating a projector onto a screen, starting
// from a scene built in Blender.
//
//   node make-project.cjs            # (re)write the project next to this script
//
// Run make-scene.py (in Blender) first: it writes assets/models/screen-venue.blend and its .glb.
//
// WHAT IS IN IT. One surface, Screen, showing a calibration TEST CARD (a shader, so the template carries
// no media): a border, a grid of square cells, a centre ring and four coloured corners. On the real
// screen that tells you at a glance whether the picture is aligned (lines on edges), undistorted
// (cells square), centred (the ring) and the right way round (the corners). The surface is routed to
// one projector output, WINDOWED so the template opens anywhere — pick the real projector's display
// in Projection Outputs. The venue is the .blend ITSELF (SceneModel.source), loaded with its own
// origin so ArtLux coordinates are Blender's; screen_main shows the Screen surface, and
// projector_main is where the Manual calibration starts.

const { writeFileSync } = require('node:fs');
const { join } = require('node:path');

const OUT = join(__dirname, 'manual-calibration.artlux');

// The test card. uv runs 0..1 across the surface; v = 1 is the TOP edge of the picture (checked on the
// stage, the projector and the 3D view — see README "Reading the test card").
const TESTCARD = `/*{
  "TITLE": "Calibration test card",
  "CATEGORIES": ["utility"],
  "INPUTS": [
    { "NAME": "line", "LABEL": "Line width", "TYPE": "float", "MIN": 0.002, "MAX": 0.02, "DEFAULT": 0.006 },
    { "NAME": "cells", "LABEL": "Cells across", "TYPE": "float", "MIN": 4.0, "MAX": 32.0, "DEFAULT": 16.0 }
  ]
}*/
// A CALIBRATION TEST CARD — generated by make-project.cjs. Everything is measured in picture HEIGHTS
// (uv.y units; x is scaled by iAspect), so a cell is square and a line is the same width both ways on
// any aspect.
float box(vec2 p, vec2 lo, vec2 hi) { return step(lo.x, p.x) * step(p.x, hi.x) * step(lo.y, p.y) * step(p.y, hi.y); }

vec4 shaderColor(vec2 uv) {
  vec2 p = vec2(uv.x * iAspect, uv.y);          // picture-height units: x 0..iAspect, y 0..1
  vec3 col = vec3(0.07);

  // Grid of square cells, "cells" of them across the width.
  float cell = iAspect / cells;
  vec2 g = abs(fract(p / cell + 0.5) - 0.5) * cell;
  col = mix(col, vec3(0.42), step(min(g.x, g.y), line * 0.5));

  // Centre: a ring a third of the height across, and a cross through it.
  vec2 c = p - vec2(iAspect * 0.5, 0.5);
  col = mix(col, vec3(1.0), step(abs(length(c) - 0.17), line * 0.6));
  col = mix(col, vec3(1.0), step(min(abs(c.x), abs(c.y)), line * 0.5) * step(length(c), 0.22));

  // Four coloured corners — TOP-LEFT red, TOP-RIGHT green, BOTTOM-RIGHT blue, BOTTOM-LEFT yellow.
  float s = 0.11;
  col = mix(col, vec3(0.95, 0.15, 0.15), box(p, vec2(0.0, 1.0 - s), vec2(s, 1.0)));
  col = mix(col, vec3(0.15, 0.85, 0.30), box(p, vec2(iAspect - s, 1.0 - s), vec2(iAspect, 1.0)));
  col = mix(col, vec3(0.20, 0.45, 1.00), box(p, vec2(iAspect - s, 0.0), vec2(iAspect, s)));
  col = mix(col, vec3(1.00, 0.85, 0.10), box(p, vec2(0.0, 0.0), vec2(s, s)));

  // An arrow above the ring, pointing UP — readable without remembering the colours.
  vec2 a = c - vec2(0.0, 0.30);
  float tri = step(0.0, a.y) * step(a.y, 0.08) * step(abs(a.x), (0.08 - a.y) * 0.75);
  col = mix(col, vec3(1.0), tri);

  // The border, last, so it is never covered: this is the line that lands on the screen's edges.
  float edge = min(min(p.x, iAspect - p.x), min(p.y, 1.0 - p.y));
  col = mix(col, vec3(1.0), step(edge, line * 1.5));
  return vec4(col, 1.0);
}`;

// THE PROJECT, as a function of the venue file — the curved-calibration template builds the same
// project around a different .blend (examples/curved-calibration/make-project.cjs requires this).
function buildProject(venueName) {
  const SCREEN = {
    id: 'srf_screen', name: 'Screen', x: 0.1, y: 0.1, width: 0.8, height: 0.45, rotation: 0, zIndex: 0,
    aspect: '16:9', portrait: false,
    content: { type: 'SHADER', shaderId: 'plasma', shaderSource: TESTCARD, shaderRes: 1080, opacity: 1 },
  };
  // The venue: the .blend itself. `origin: 'file'` keeps Blender's coordinates (the screen 2 m up and
  // 3 m back, the projector 9 m in front of it) — see SceneModel.origin.
  const VENUE = {
    id: 'mdl_venue', name: venueName, kind: 'mesh',
    source: `assets/models/${venueName}.blend`, path: `assets/models/${venueName}.glb`, origin: 'file',
    position: { x: 0, y: 0, z: 0 }, rotation: { x: 0, y: 0, z: 0 }, scale: 1, visible: true,
    screens: { screen_main: { surfaceId: SCREEN.id } },
  };
  return {
    version: '1.2',
    timestamp: new Date(0).toISOString(),
    globalBrightness: 1,
    groups: [],
    scenes: [],
    cueBanks: [],
    schedule: undefined,
    assets: [{ id: 'asset_venue', name: venueName, type: 'model', path: VENUE.source }],
    projectorOutputs: [{
      surfaceId: SCREEN.id, name: 'Screen', enabled: true, displayId: -1, // windowed: opens on any machine
      cornerPin: { tl: [0, 0], tr: [1, 0], br: [1, 1], bl: [0, 1] }, warp: null,
      softEdge: { left: 0, right: 0, top: 0, bottom: 0, gamma: 2.2 }, gamma: 1,
    }],
    // Loopback: opening the template transmits nothing to real fixtures.
    controllers: [{ id: 'ctl_local', name: 'Loopback', protocol: 'artnet', ip: '127.0.0.1', broadcast: false, startUniverse: 0 }],
    scene3D: {
      models: [VENUE], lightIntensity: 1, environment: true, exposure: 1, gridVisible: true,
      reflectiveFloor: false, trackingViz: false, augmentaViz: false, trackingSmoothing: 0.6, trackingPredictMs: 50,
    },
    timeline: { layers: [], clips: [], duration: 40, fps: 30, markers: [], inPoint: null, outPoint: null, loop: true, trackingTakes: [] },
    surfaces: [SCREEN],
    fixtures: [],
  };
}

module.exports = { buildProject, TESTCARD };

if (require.main === module) {
  writeFileSync(OUT, JSON.stringify(buildProject('screen-venue'), null, 2) + '\n');
  console.log(`wrote ${OUT}`);
}
